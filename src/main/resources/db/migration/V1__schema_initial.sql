-- =====================================================================================
-- V1 : schéma initial de l'Outil de quiz dynamique IUT
-- Source : Dossier de conception et d'architecture technique, §3.2 (MLD, 20 tables)
--          et §3.2.3 (dictionnaire des données).
--
-- Conventions :
--  - noms en snake_case (PostgreSQL met en minuscules les noms non quotés, et c'est la
--    stratégie de nommage par défaut de Spring/Hibernate : idEnseignant -> id_enseignant) ;
--  - listes de valeurs en colonnes texte avec contrainte CHECK ;
--  - clés étrangères indexées (PostgreSQL ne le fait pas automatiquement), sauf quand un
--    index UNIQUE ou une clé primaire commence déjà par la colonne ;
--  - la suppression d'une session supprime en cascade ses participants, leurs réponses
--    (avec REPONSE_CHOIX et REPONSE_LIEN) et ses corrections (purge RGPD) ;
--  - les autres clés étrangères refusent la suppression (NO ACTION, vérifié en fin
--    d'instruction : la cascade d'une session peut ainsi supprimer réponses et corrections
--    dans n'importe quel ordre).
--
-- Les contraintes d'intégrité qui portent sur plusieurs associations (§3.1.5 : même cours,
-- même enseignant, même question…) sont vérifiées par le back-end.
-- =====================================================================================


-- -------------------------------------------------------------------------------------
-- Cours, versions, quiz et classements
-- -------------------------------------------------------------------------------------

CREATE TABLE enseignant (
    id_enseignant     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifiant_ldap  VARCHAR(64)  NOT NULL UNIQUE,
    nom               VARCHAR(100) NOT NULL,
    prenom            VARCHAR(100) NOT NULL,
    origine_compte    VARCHAR(10)  NOT NULL,
    role              VARCHAR(15)  NOT NULL DEFAULT 'ENSEIGNANT',
    mot_de_passe_hash VARCHAR(100),
    date_creation     TIMESTAMP    NOT NULL,
    CONSTRAINT ck_enseignant_origine CHECK (origine_compte IN ('LDAP', 'LOCAL')),
    CONSTRAINT ck_enseignant_role    CHECK (role IN ('ENSEIGNANT', 'ADMINISTRATEUR')),
    -- Empreinte BCrypt uniquement pour un compte LOCAL : aucun mot de passe LDAP n'est conservé.
    CONSTRAINT ck_enseignant_mot_de_passe CHECK (origine_compte = 'LOCAL' OR mot_de_passe_hash IS NULL)
);

CREATE TABLE cours (
    id_cours          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre             VARCHAR(200) NOT NULL,
    date_creation     TIMESTAMP    NOT NULL,
    date_modification TIMESTAMP    NOT NULL,
    archive           BOOLEAN      NOT NULL DEFAULT FALSE,
    id_enseignant     BIGINT       NOT NULL REFERENCES enseignant (id_enseignant),
    CONSTRAINT ck_cours_titre CHECK (btrim(titre) <> '')
);
CREATE INDEX ix_cours_enseignant ON cours (id_enseignant);

CREATE TABLE version_cours (
    id_version               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero                   INT          NOT NULL,
    nom_fichier              VARCHAR(255) NOT NULL,
    chemin_stockage          VARCHAR(500),
    taille_octets            BIGINT       NOT NULL,
    nb_pages                 INT          NOT NULL,
    empreinte                CHAR(64)     NOT NULL,
    date_import              TIMESTAMP    NOT NULL,
    date_suppression_fichier TIMESTAMP,
    id_cours                 BIGINT       NOT NULL REFERENCES cours (id_cours),
    CONSTRAINT uq_version_cours_numero UNIQUE (id_cours, numero),
    CONSTRAINT ck_version_cours_numero CHECK (numero >= 1),
    CONSTRAINT ck_version_cours_taille CHECK (taille_octets >= 0),
    CONSTRAINT ck_version_cours_pages  CHECK (nb_pages >= 1),
    -- Fichier supprimé par l'administrateur (UC20) : plus de chemin, une date de suppression.
    CONSTRAINT ck_version_cours_fichier CHECK ((chemin_stockage IS NULL) = (date_suppression_fichier IS NOT NULL))
);

CREATE TABLE quiz (
    id_quiz                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre                  VARCHAR(200) NOT NULL,
    est_note               BOOLEAN      NOT NULL DEFAULT FALSE,
    duree_par_defaut_sec   INT          NOT NULL,
    passage_automatique    BOOLEAN      NOT NULL DEFAULT FALSE,
    delai_passage_auto_sec INT,
    affichage_cours        VARCHAR(20)  NOT NULL,
    archive                BOOLEAN      NOT NULL DEFAULT FALSE,
    id_cours               BIGINT       NOT NULL REFERENCES cours (id_cours),
    CONSTRAINT ck_quiz_duree           CHECK (duree_par_defaut_sec > 0),
    CONSTRAINT ck_quiz_delai           CHECK (delai_passage_auto_sec IS NULL OR delai_passage_auto_sec >= 0),
    CONSTRAINT ck_quiz_affichage_cours CHECK (affichage_cours IN ('PROJETE_SEUL', 'AUSSI_ETUDIANTS'))
);
CREATE INDEX ix_quiz_cours ON quiz (id_cours);

CREATE TABLE classement (
    id_classement BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom           VARCHAR(150) NOT NULL,
    id_enseignant BIGINT       NOT NULL REFERENCES enseignant (id_enseignant),
    CONSTRAINT uq_classement_nom UNIQUE (id_enseignant, nom)
);

CREATE TABLE classement_quiz (
    id_classement BIGINT NOT NULL REFERENCES classement (id_classement),
    id_quiz       BIGINT NOT NULL REFERENCES quiz (id_quiz),
    PRIMARY KEY (id_classement, id_quiz)
);
CREATE INDEX ix_classement_quiz_quiz ON classement_quiz (id_quiz);


-- -------------------------------------------------------------------------------------
-- Questions et contenu attendu
-- -------------------------------------------------------------------------------------

CREATE TABLE question (
    id_question        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type               VARCHAR(20) NOT NULL,
    enonce             TEXT        NOT NULL,
    duree_sec          INT,
    points_max         INT         NOT NULL DEFAULT 1000,
    decroissance_temps BOOLEAN     NOT NULL,
    points_partiels    BOOLEAN     NOT NULL,
    verrouillee        BOOLEAN     NOT NULL DEFAULT FALSE,
    archivee           BOOLEAN     NOT NULL DEFAULT FALSE,
    id_quiz            BIGINT      NOT NULL REFERENCES quiz (id_quiz),
    -- Types MUST/SHOULD ; les types COULD (vrai/faux, remise dans l'ordre, sondage) seront
    -- ajoutés par une migration qui élargit cette contrainte.
    CONSTRAINT ck_question_type       CHECK (type IN ('QCM', 'POINTS_A_RELIER', 'REPONSE_LIBRE')),
    CONSTRAINT ck_question_duree      CHECK (duree_sec IS NULL OR duree_sec > 0),
    CONSTRAINT ck_question_points_max CHECK (points_max >= 0)
);
CREATE INDEX ix_question_quiz ON question (id_quiz);

CREATE TABLE proposition (
    id_proposition BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle        VARCHAR(500) NOT NULL,
    est_correcte   BOOLEAN      NOT NULL,
    rang           INT          NOT NULL,
    id_question    BIGINT       NOT NULL REFERENCES question (id_question)
);
CREATE INDEX ix_proposition_question ON proposition (id_question);

CREATE TABLE paire (
    id_paire       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    element_gauche VARCHAR(300) NOT NULL,
    element_droit  VARCHAR(300) NOT NULL,
    id_question    BIGINT       NOT NULL REFERENCES question (id_question)
);
CREATE INDEX ix_paire_question ON paire (id_question);

CREATE TABLE motif (
    id_motif    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    motif       VARCHAR(500) NOT NULL,
    mode_motif  VARCHAR(10)  NOT NULL,
    id_question BIGINT       NOT NULL REFERENCES question (id_question),
    CONSTRAINT ck_motif_mode CHECK (mode_motif IN ('SIMPLE', 'REGEX'))
);
CREATE INDEX ix_motif_question ON motif (id_question);

CREATE TABLE image (
    id_image                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_fichier              VARCHAR(255) NOT NULL,
    chemin_stockage          VARCHAR(500),
    type_mime                VARCHAR(20)  NOT NULL,
    taille_octets            BIGINT       NOT NULL,
    largeur                  INT          NOT NULL,
    hauteur                  INT          NOT NULL,
    empreinte                CHAR(64)     NOT NULL,
    date_ajout               TIMESTAMP    NOT NULL,
    date_suppression_fichier TIMESTAMP,
    id_enseignant            BIGINT       NOT NULL REFERENCES enseignant (id_enseignant),
    -- NULL = image orpheline (UC19) ; au plus une image par question.
    id_question              BIGINT       UNIQUE REFERENCES question (id_question),
    CONSTRAINT ck_image_type_mime  CHECK (type_mime IN ('image/png', 'image/jpeg', 'image/webp')),
    CONSTRAINT ck_image_taille     CHECK (taille_octets >= 0),
    CONSTRAINT ck_image_dimensions CHECK (largeur > 0 AND hauteur > 0),
    CONSTRAINT ck_image_fichier    CHECK ((chemin_stockage IS NULL) = (date_suppression_fichier IS NOT NULL))
);
CREATE INDEX ix_image_enseignant ON image (id_enseignant);

CREATE TABLE ecran_intermediaire (
    id_ecran                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_ecran              VARCHAR(20) NOT NULL,
    rang                    INT         NOT NULL,
    delai_apres_cloture_sec INT         NOT NULL DEFAULT 0,
    parametres              JSONB,
    id_question             BIGINT      NOT NULL REFERENCES question (id_question),
    CONSTRAINT ck_ecran_type  CHECK (type_ecran IN ('BONNE_REPONSE', 'REPARTITION', 'CLASSEMENT')),
    CONSTRAINT ck_ecran_delai CHECK (delai_apres_cloture_sec >= 0)
);
CREATE INDEX ix_ecran_intermediaire_question ON ecran_intermediaire (id_question);


-- -------------------------------------------------------------------------------------
-- Pages insérées dans une version du cours
-- -------------------------------------------------------------------------------------

CREATE TABLE page_inseree (
    id_page       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_page   INT          NOT NULL,
    repere_texte  VARCHAR(300),
    ordre         INT          NOT NULL,
    valide        BOOLEAN      NOT NULL,
    id_version    BIGINT       NOT NULL REFERENCES version_cours (id_version),
    id_question   BIGINT       REFERENCES question (id_question),
    id_classement BIGINT       REFERENCES classement (id_classement),
    CONSTRAINT uq_page_inseree_position UNIQUE (id_version, numero_page, ordre),
    CONSTRAINT uq_page_inseree_question UNIQUE (id_version, id_question),
    -- 0 = avant la première page du PDF.
    CONSTRAINT ck_page_inseree_numero CHECK (numero_page >= 0),
    -- Page de quiz OU page de classement, jamais les deux.
    CONSTRAINT ck_page_inseree_contenu CHECK (num_nonnulls(id_question, id_classement) = 1)
);
CREATE INDEX ix_page_inseree_question   ON page_inseree (id_question);
CREATE INDEX ix_page_inseree_classement ON page_inseree (id_classement);


-- -------------------------------------------------------------------------------------
-- Séances et résultats
-- -------------------------------------------------------------------------------------

CREATE TABLE session_quiz (
    id_session        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_acces        VARCHAR(32) NOT NULL UNIQUE,
    etat              VARCHAR(12) NOT NULL,
    est_notee         BOOLEAN     NOT NULL,
    date_lancement    TIMESTAMP,
    date_cloture      TIMESTAMP,
    position_courante INT         NOT NULL DEFAULT 0,
    echeance_question TIMESTAMP,
    id_quiz           BIGINT      NOT NULL REFERENCES quiz (id_quiz),
    id_version        BIGINT      NOT NULL REFERENCES version_cours (id_version),
    CONSTRAINT ck_session_quiz_etat     CHECK (etat IN ('PREPAREE', 'EN_COURS', 'CLOTUREE')),
    CONSTRAINT ck_session_quiz_position CHECK (position_courante >= 0)
);
CREATE INDEX ix_session_quiz_quiz    ON session_quiz (id_quiz);
CREATE INDEX ix_session_quiz_version ON session_quiz (id_version);

CREATE TABLE participant (
    id_participant    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pseudonyme        VARCHAR(20)  NOT NULL,
    identifiant_ldap  VARCHAR(64),
    nom               VARCHAR(100),
    prenom            VARCHAR(100),
    identite_verifiee BOOLEAN      NOT NULL,
    score_total       INT          NOT NULL DEFAULT 0,
    date_entree       TIMESTAMP    NOT NULL,
    jeton_reconnexion CHAR(64)     NOT NULL UNIQUE,
    derniere_activite TIMESTAMP    NOT NULL,
    id_session        BIGINT       NOT NULL REFERENCES session_quiz (id_session) ON DELETE CASCADE,
    CONSTRAINT uq_participant_pseudonyme UNIQUE (id_session, pseudonyme),
    CONSTRAINT uq_participant_ldap       UNIQUE (id_session, identifiant_ldap),
    -- 2 à 20 caractères (hypothèse du dossier).
    CONSTRAINT ck_participant_pseudonyme CHECK (char_length(btrim(pseudonyme)) >= 2)
);

CREATE TABLE correction (
    id_correction    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texte_normalise  VARCHAR(1000) NOT NULL,
    decision         VARCHAR(10)   NOT NULL,
    date_decision    TIMESTAMP     NOT NULL,
    id_enseignant    BIGINT        NOT NULL REFERENCES enseignant (id_enseignant),
    id_session       BIGINT        NOT NULL REFERENCES session_quiz (id_session) ON DELETE CASCADE,
    id_question      BIGINT        NOT NULL REFERENCES question (id_question),
    CONSTRAINT uq_correction_texte    UNIQUE (id_session, id_question, texte_normalise),
    CONSTRAINT ck_correction_decision CHECK (decision IN ('VALIDEE', 'REFUSEE'))
);
CREATE INDEX ix_correction_enseignant ON correction (id_enseignant);
CREATE INDEX ix_correction_question   ON correction (id_question);

CREATE TABLE reponse (
    id_reponse         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    horodatage_serveur TIMESTAMP     NOT NULL,
    temps_reponse_ms   INT           NOT NULL,
    texte_libre        VARCHAR(1000),
    points_calcules    INT           NOT NULL,
    points_finaux      INT           NOT NULL,
    statut_correction  VARCHAR(20)   NOT NULL,
    id_participant     BIGINT        NOT NULL REFERENCES participant (id_participant) ON DELETE CASCADE,
    id_question        BIGINT        NOT NULL REFERENCES question (id_question),
    id_correction      BIGINT        REFERENCES correction (id_correction),
    -- Une seule réponse par participant et par question.
    CONSTRAINT uq_reponse_participant_question UNIQUE (id_participant, id_question),
    CONSTRAINT ck_reponse_temps  CHECK (temps_reponse_ms >= 0),
    CONSTRAINT ck_reponse_statut CHECK (statut_correction IN
        ('SANS_OBJET', 'ACCEPTEE_PAR_MOTIF', 'A_EXAMINER', 'VALIDEE', 'REFUSEE'))
);
CREATE INDEX ix_reponse_question   ON reponse (id_question);
CREATE INDEX ix_reponse_correction ON reponse (id_correction);

CREATE TABLE reponse_choix (
    id_reponse     BIGINT NOT NULL REFERENCES reponse (id_reponse) ON DELETE CASCADE,
    id_proposition BIGINT NOT NULL REFERENCES proposition (id_proposition),
    PRIMARY KEY (id_reponse, id_proposition)
);
CREATE INDEX ix_reponse_choix_proposition ON reponse_choix (id_proposition);

CREATE TABLE reponse_lien (
    id_reponse      BIGINT NOT NULL REFERENCES reponse (id_reponse) ON DELETE CASCADE,
    id_paire_gauche BIGINT NOT NULL REFERENCES paire (id_paire),
    id_paire_droite BIGINT NOT NULL REFERENCES paire (id_paire),
    PRIMARY KEY (id_reponse, id_paire_gauche),
    -- Un élément de droite n'est relié qu'une fois par réponse.
    CONSTRAINT uq_reponse_lien_droite UNIQUE (id_reponse, id_paire_droite)
);
CREATE INDEX ix_reponse_lien_gauche ON reponse_lien (id_paire_gauche);
CREATE INDEX ix_reponse_lien_droite ON reponse_lien (id_paire_droite);


-- -------------------------------------------------------------------------------------
-- Journal des connexions et des actions sensibles
-- Aucune clé étrangère : purgé indépendamment (conservation 6 mois).
-- -------------------------------------------------------------------------------------

CREATE TABLE journal_evenement (
    id_evenement BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_heure   TIMESTAMP    NOT NULL,
    acteur       VARCHAR(64),
    type_action  VARCHAR(30)  NOT NULL,
    cible        VARCHAR(100),
    adresse_ip   VARCHAR(45),
    details      TEXT
);
-- Sert à la purge par date.
CREATE INDEX ix_journal_evenement_date ON journal_evenement (date_heure);
